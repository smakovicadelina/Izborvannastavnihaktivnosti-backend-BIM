CREATE EXTENSION IF NOT EXISTS btree_gist;

-- -----------------------------------------------------------------------------
-- KORISNICI - profil; id je isti kao u auth.users (Supabase Auth), veza 1:1
-- -----------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'uloga_korisnika') THEN
        CREATE TYPE public.uloga_korisnika AS ENUM ('ucenik', 'profesor');
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.korisnici (
    id               UUID PRIMARY KEY
                     REFERENCES auth.users(id) ON DELETE CASCADE,
    ime_i_prezime    TEXT NOT NULL,
    uloga            public.uloga_korisnika NOT NULL DEFAULT 'ucenik',
    razred_odeljenje TEXT,
    korisnicko_ime   TEXT,
    biografija       TEXT,
    avatar_url       TEXT,
    kreirano_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS korisnici_korisnicko_ime_uq
    ON public.korisnici (LOWER(korisnicko_ime))
    WHERE korisnicko_ime IS NOT NULL;

-- -----------------------------------------------------------------------------
-- SIFARNICI
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.kategorije (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv TEXT NOT NULL UNIQUE,
    opis  TEXT
);

CREATE TABLE IF NOT EXISTS public.interesovanja (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv TEXT NOT NULL UNIQUE,
    opis  TEXT
);

-- Veza N:N korisnik <-> interesovanje
CREATE TABLE IF NOT EXISTS public.korisnik_interesovanja (
    korisnik_id      UUID   NOT NULL REFERENCES public.korisnici(id) ON DELETE CASCADE,
    interesovanje_id BIGINT NOT NULL REFERENCES public.interesovanja(id) ON DELETE RESTRICT,
    PRIMARY KEY (korisnik_id, interesovanje_id)
);

-- -----------------------------------------------------------------------------
-- PROSTORIJE I TERMINI (migracije 001 i 002)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.prostorije (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv     TEXT NOT NULL UNIQUE,
    kapacitet INTEGER NOT NULL CHECK (kapacitet > 0),
    opis      TEXT
);

CREATE TABLE IF NOT EXISTS public.termini (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dan_u_nedelji INTEGER NOT NULL CHECK (dan_u_nedelji BETWEEN 1 AND 7),
    vreme_od      TIME NOT NULL,
    vreme_do      TIME NOT NULL,
    prostorija_id BIGINT NOT NULL REFERENCES public.prostorije(id) ON DELETE RESTRICT,
    kreirano_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT validno_vreme CHECK (vreme_od < vreme_do)
);
-- Zabrana preklapanja termina u istoj prostoriji: vidi 002_termini.sql (EXCLUDE USING gist).

-- -----------------------------------------------------------------------------
-- AKTIVNOSTI
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.aktivnosti (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv            TEXT NOT NULL,
    opis             TEXT,
    maksimalno_mesta INTEGER NOT NULL CHECK (maksimalno_mesta > 0),
    termin           TEXT NOT NULL,          -- citljiv opis, npr. "Sreda 14:00–15:30"
    prostorija       TEXT,                   -- citljiv naziv prostorije
    aktivna          BOOLEAN NOT NULL DEFAULT TRUE,
    slika_url        TEXT,
    kategorija_id    BIGINT REFERENCES public.kategorije(id) ON DELETE RESTRICT,
    profesor_id      UUID   REFERENCES public.korisnici(id) ON DELETE SET NULL, -- kreator
    termin_id        BIGINT REFERENCES public.termini(id) ON DELETE RESTRICT,   -- glavni termin
    kreirano_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Veza N:N aktivnost <-> termin
CREATE TABLE IF NOT EXISTS public.aktivnost_termini (
    aktivnost_id BIGINT NOT NULL REFERENCES public.aktivnosti(id) ON DELETE CASCADE,
    termin_id    BIGINT NOT NULL REFERENCES public.termini(id) ON DELETE RESTRICT,
    PRIMARY KEY (aktivnost_id, termin_id)
);

-- Veza N:N aktivnost <-> profesor (korisnik sa ulogom profesor)
CREATE TABLE IF NOT EXISTS public.aktivnost_profesori (
    aktivnost_id BIGINT NOT NULL REFERENCES public.aktivnosti(id) ON DELETE CASCADE,
    profesor_id  UUID   NOT NULL REFERENCES public.korisnici(id) ON DELETE CASCADE,
    PRIMARY KEY (aktivnost_id, profesor_id)
);

-- Veza N:N aktivnost <-> interesovanje (migracija 004)
CREATE TABLE IF NOT EXISTS public.aktivnost_interesovanja (
    aktivnost_id     BIGINT NOT NULL REFERENCES public.aktivnosti(id) ON DELETE CASCADE,
    interesovanje_id BIGINT NOT NULL REFERENCES public.interesovanja(id) ON DELETE RESTRICT,
    PRIMARY KEY (aktivnost_id, interesovanje_id)
);

-- -----------------------------------------------------------------------------
-- PRIJAVE (ucenik <-> aktivnost, sa atributima veze) i PRISUSTVO
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.prijave (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ucenik_id      UUID   NOT NULL REFERENCES public.korisnici(id) ON DELETE RESTRICT,
    aktivnost_id   BIGINT NOT NULL REFERENCES public.aktivnosti(id) ON DELETE RESTRICT,
    status_prijave TEXT   NOT NULL DEFAULT 'prijavljen'
                   CHECK (status_prijave IN ('prijavljen', 'na_cekanju', 'otkazano')),
    prijavljen_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Ucenik moze imati najvise jednu AKTIVNU prijavu na istu aktivnost.
CREATE UNIQUE INDEX IF NOT EXISTS prijave_aktivna_uq
    ON public.prijave (ucenik_id, aktivnost_id)
    WHERE status_prijave IN ('prijavljen', 'na_cekanju');

CREATE TABLE IF NOT EXISTS public.prisustva (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prijava_id      BIGINT  NOT NULL REFERENCES public.prijave(id) ON DELETE CASCADE,
    datum           DATE    NOT NULL DEFAULT CURRENT_DATE,
    prisutan        BOOLEAN NOT NULL DEFAULT TRUE,
    evidentirano_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS prisustva_prijava_datum_uq
    ON public.prisustva (prijava_id, datum);

-- -----------------------------------------------------------------------------
-- OBAVESTENJA, AI PREPORUKE, ZAHTEVI ZA PROFESORA
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.obavestenja (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    korisnik_id  UUID NOT NULL REFERENCES public.korisnici(id) ON DELETE CASCADE,
    tip          TEXT NOT NULL,
    naslov       TEXT NOT NULL,
    poruka       TEXT NOT NULL,
    aktivnost_id BIGINT REFERENCES public.aktivnosti(id) ON DELETE SET NULL,
    procitano    BOOLEAN NOT NULL DEFAULT FALSE,
    kreirano_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.ai_preporuke (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    korisnik_id UUID NOT NULL REFERENCES public.korisnici(id) ON DELETE CASCADE,
    pitanje     TEXT NOT NULL,
    odgovor     TEXT NOT NULL,                -- JSON: { uvod, preporuke[], model, izvor }
    kreirano_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Veza N:N AI preporuka <-> preporucena aktivnost
CREATE TABLE IF NOT EXISTS public.ai_preporuka_aktivnosti (
    preporuka_id BIGINT NOT NULL REFERENCES public.ai_preporuke(id) ON DELETE CASCADE,
    aktivnost_id BIGINT NOT NULL REFERENCES public.aktivnosti(id) ON DELETE CASCADE,
    PRIMARY KEY (preporuka_id, aktivnost_id)
);

CREATE TABLE IF NOT EXISTS public.zahtevi_za_profesora (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    korisnik_id UUID NOT NULL UNIQUE REFERENCES public.korisnici(id) ON DELETE RESTRICT,
    status      TEXT NOT NULL DEFAULT 'na_cekanju'
                CHECK (status IN ('na_cekanju', 'odobren', 'odbijen')),
    kreiran_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    obradjen_at TIMESTAMPTZ
);

