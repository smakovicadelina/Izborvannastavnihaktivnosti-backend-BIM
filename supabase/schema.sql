-- -----------------------------------------------------------------------------
-- RPC: bezbedna_prijava - prijava ucenika u JEDNOJ transakciji.
-- Zakljucava red aktivnosti (FOR UPDATE), pa dve istovremene prijave na
-- poslednje mesto ne mogu obe uspeti. Backend je poziva sa
-- dbSupabase.rpc("bezbedna_prijava", { p_ucenik_id, p_aktivnost_id }).
-- Poruke gresaka backend prevodi u HTTP 404/403/409 (prijavaService.js).
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.bezbedna_prijava(
    p_ucenik_id    UUID,
    p_aktivnost_id BIGINT
)
RETURNS public.prijave
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_aktivnost public.aktivnosti;
    v_prijava   public.prijave;
    v_zauzeto   INTEGER;
BEGIN
    SELECT * INTO v_aktivnost
      FROM public.aktivnosti
     WHERE id = p_aktivnost_id
       FOR UPDATE;

    IF NOT FOUND OR NOT v_aktivnost.aktivna THEN
        RAISE EXCEPTION 'Aktivnost nije dostupna.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM public.korisnici
         WHERE id = p_ucenik_id AND uloga = 'ucenik'
    ) THEN
        RAISE EXCEPTION 'Prijava je dozvoljena samo učenicima.';
    END IF;

    IF EXISTS (
        SELECT 1 FROM public.prijave
         WHERE ucenik_id = p_ucenik_id
           AND aktivnost_id = p_aktivnost_id
           AND status_prijave IN ('prijavljen', 'na_cekanju')
    ) THEN
        RAISE EXCEPTION 'Već ste prijavljeni na ovu aktivnost.';
    END IF;

    SELECT COUNT(*) INTO v_zauzeto
      FROM public.prijave
     WHERE aktivnost_id = p_aktivnost_id
       AND status_prijave = 'prijavljen';

    IF v_zauzeto >= v_aktivnost.maksimalno_mesta THEN
        RAISE EXCEPTION 'Nema slobodnih mesta na ovoj aktivnosti.';
    END IF;

    INSERT INTO public.prijave (ucenik_id, aktivnost_id, status_prijave)
    VALUES (p_ucenik_id, p_aktivnost_id, 'prijavljen')
    RETURNING * INTO v_prijava;

    RETURN v_prijava;
END;
$$;

REVOKE ALL ON FUNCTION public.bezbedna_prijava(UUID, BIGINT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.bezbedna_prijava(UUID, BIGINT) TO service_role;

NOTIFY pgrst, 'reload schema';
