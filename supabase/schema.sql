--
-- Glavni entiteti i veze:
--   KORISNIK (ucenik / profesor) 1 --- N PRIJAVA N --- 1 AKTIVNOST
--   AKTIVNOST N --- 1 KATEGORIJA
--   AKTIVNOST N --- N TERMIN        (aktivnost_termini)   TERMIN N --- 1 PROSTORIJA
--   AKTIVNOST N --- N PROFESOR      (aktivnost_profesori)
--   AKTIVNOST N --- N INTERESOVANJE (aktivnost_interesovanja)
--   KORISNIK  N --- N INTERESOVANJE (korisnik_interesovanja)
--   PRIJAVA   1 --- N PRISUSTVO
--   KORISNIK  1 --- N OBAVESTENJE, AI_PREPORUKA; 1 --- 0..1 ZAHTEV_ZA_PROFESORA
