-- Dodaje: obavestenja, vezu aktivnost–interesovanje i jedinstveno prisustvo po danu.
-- Bezbedno za ponovno pokretanje (IF NOT EXISTS).

-- 1) OBAVESTENJA (promene termina, prijave, otkazivanja...)
CREATE TABLE IF NOT EXISTS public.obavestenja (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    korisnik_id UUID NOT NULL
        REFERENCES public.korisnici(id) ON DELETE CASCADE,
    tip TEXT NOT NULL,
    naslov TEXT NOT NULL,
    poruka TEXT NOT NULL,
    aktivnost_id BIGINT
        REFERENCES public.aktivnosti(id) ON DELETE SET NULL,
    procitano BOOLEAN NOT NULL DEFAULT FALSE,
    kreirano_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_obavestenja_korisnik
    ON public.obavestenja (korisnik_id, procitano, kreirano_at DESC);

-- 2) VEZA AKTIVNOST – INTERESOVANJE (filtriranje i AI preporuke)
CREATE TABLE IF NOT EXISTS public.aktivnost_interesovanja (
    aktivnost_id BIGINT NOT NULL
        REFERENCES public.aktivnosti(id) ON DELETE CASCADE,
    interesovanje_id BIGINT NOT NULL
        REFERENCES public.interesovanja(id) ON DELETE RESTRICT,
    PRIMARY KEY (aktivnost_id, interesovanje_id)
);

CREATE INDEX IF NOT EXISTS idx_aktivnost_interesovanja_interesovanje
    ON public.aktivnost_interesovanja (interesovanje_id);

-- 3) Jedno evidentirano prisustvo po prijavi i datumu (QR skeniranje je idempotentno)
CREATE UNIQUE INDEX IF NOT EXISTS prisustva_prijava_datum_uq
    ON public.prisustva (prijava_id, datum);

-- 4) Prava pristupa: tabelama pristupa samo backend (service_role).
ALTER TABLE public.obavestenja ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.aktivnost_interesovanja ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.obavestenja FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.aktivnost_interesovanja FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.obavestenja_id_seq FROM PUBLIC, anon, authenticated;

GRANT ALL ON public.obavestenja TO service_role;
GRANT ALL ON public.aktivnost_interesovanja TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.obavestenja_id_seq TO service_role;

NOTIFY pgrst, 'reload schema';
