-- Run manually after verifying the existing Auth trigger and profile schema.
-- Adds a pending-request table and replaces only the existing trigger function.

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_trigger AS trigger_info
        JOIN pg_proc AS trigger_function
          ON trigger_function.oid = trigger_info.tgfoid
        WHERE trigger_info.tgrelid = 'auth.users'::regclass
          AND trigger_info.tgname = 'na_registraciju_korisnika'
          AND NOT trigger_info.tgisinternal
          AND trigger_function.oid =
              'public.obradi_novog_korisnika()'::regprocedure
    ) THEN
        RAISE EXCEPTION
            'Ocekivani trigger na_registraciju_korisnika nije vezan za public.obradi_novog_korisnika().';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_attribute
        WHERE attrelid = 'public.korisnici'::regclass
          AND attname = 'ime_i_prezime'
          AND NOT attisdropped
    ) THEN
        RAISE EXCEPTION
            'public.korisnici nema ocekivanu kolonu ime_i_prezime.';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_attribute
        WHERE attrelid = 'public.korisnici'::regclass
          AND attname = 'uloga'
          AND atttypid = 'public.uloga_korisnika'::regtype
          AND NOT attisdropped
    ) THEN
        RAISE EXCEPTION
            'public.korisnici.uloga nije tipa public.uloga_korisnika.';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'korisnici'
          AND is_nullable = 'NO'
          AND column_name NOT IN ('id', 'ime_i_prezime', 'uloga')
          AND column_default IS NULL
          AND is_identity = 'NO'
          AND is_generated = 'NEVER'
    ) THEN
        RAISE EXCEPTION
            'public.korisnici ima dodatne obavezne kolone bez podrazumijevane vrijednosti; pregledajte semu prije zamjene trigger funkcije.';
    END IF;

    IF EXISTS (
        SELECT required_role.role_name
        FROM (VALUES ('ucenik'), ('profesor')) AS required_role(role_name)
        WHERE NOT EXISTS (
            SELECT 1
            FROM pg_enum
            WHERE enumtypid = 'public.uloga_korisnika'::regtype
              AND enumlabel = required_role.role_name
        )
    ) THEN
        RAISE EXCEPTION
            'Tip public.uloga_korisnika mora sadrzati ucenik i profesor.';
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.zahtevi_za_profesora (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    korisnik_id UUID NOT NULL UNIQUE
        REFERENCES public.korisnici(id) ON DELETE RESTRICT,
    status TEXT NOT NULL DEFAULT 'na_cekanju'
        CHECK (status IN ('na_cekanju', 'odobren', 'odbijen')),
    kreiran_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    obradjen_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_zahtevi_za_profesora_status
    ON public.zahtevi_za_profesora (status, kreiran_at);

ALTER TABLE public.korisnici ENABLE ROW LEVEL SECURITY;
REVOKE INSERT, UPDATE, DELETE
    ON public.korisnici
    FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.korisnici TO service_role;

ALTER TABLE public.zahtevi_za_profesora ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.zahtevi_za_profesora
    FROM PUBLIC, anon, authenticated;
REVOKE ALL
    ON SEQUENCE public.zahtevi_za_profesora_id_seq
    FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.zahtevi_za_profesora TO service_role;
GRANT USAGE, SELECT
    ON SEQUENCE public.zahtevi_za_profesora_id_seq
    TO service_role;

CREATE OR REPLACE FUNCTION public.obradi_novog_korisnika()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    ime TEXT;
BEGIN
    ime := COALESCE(
        NULLIF(BTRIM(NEW.raw_user_meta_data ->> 'ime_i_prezime'), ''),
        NULLIF(SPLIT_PART(COALESCE(NEW.email, ''), '@', 1), ''),
        'Korisnik'
    );

    INSERT INTO public.korisnici (id, ime_i_prezime, uloga)
    VALUES (
        NEW.id,
        ime,
        'ucenik'::public.uloga_korisnika
    )
    ON CONFLICT (id) DO NOTHING;

    IF NEW.raw_user_meta_data ->> 'requested_role' = 'profesor' THEN
        INSERT INTO public.zahtevi_za_profesora (korisnik_id)
        VALUES (NEW.id)
        ON CONFLICT (korisnik_id) DO NOTHING;
    END IF;

    RETURN NEW;
END;
$$;

INSERT INTO public.zahtevi_za_profesora (korisnik_id)
SELECT profile.id
FROM auth.users AS auth_user
JOIN public.korisnici AS profile
  ON profile.id = auth_user.id
WHERE auth_user.raw_user_meta_data ->> 'requested_role' = 'profesor'
  AND profile.uloga = 'ucenik'::public.uloga_korisnika
ON CONFLICT (korisnik_id) DO NOTHING;

NOTIFY pgrst, 'reload schema';
