-- Kreira termine nakon prostorija; ne menja postojeće aktivnosti i prijave.
CREATE TABLE IF NOT EXISTS public.termini (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dan_u_nedelji INTEGER NOT NULL
        CHECK (dan_u_nedelji BETWEEN 1 AND 7),
    vreme_od TIME NOT NULL,
    vreme_do TIME NOT NULL,
    prostorija_id BIGINT NOT NULL
        REFERENCES public.prostorije(id)
        ON DELETE RESTRICT,
    kreirano_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT validno_vreme CHECK (vreme_od < vreme_do)
);

CREATE INDEX IF NOT EXISTS idx_termini_prostorija
    ON public.termini (prostorija_id);

CREATE INDEX IF NOT EXISTS idx_termini_dan
    ON public.termini (dan_u_nedelji);

CREATE EXTENSION IF NOT EXISTS btree_gist;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'termini_bez_preklapanja'
          AND conrelid = 'public.termini'::regclass
    ) THEN
        ALTER TABLE public.termini
        ADD CONSTRAINT termini_bez_preklapanja
        EXCLUDE USING gist (
            prostorija_id WITH =,
            dan_u_nedelji WITH =,
            tsrange(
                DATE '2000-01-01' + vreme_od,
                DATE '2000-01-01' + vreme_do,
                '[)'
            ) WITH &&
        );
    END IF;
END
$$;

ALTER TABLE public.termini ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.termini FROM anon;
GRANT SELECT ON public.termini TO authenticated;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'termini'
          AND policyname = 'Pregled termina'
    ) THEN
        CREATE POLICY "Pregled termina"
        ON public.termini
        FOR SELECT
        TO authenticated
        USING (true);
    END IF;
END
$$;
